#!/usr/bin/env python3
"""Turn the packed sprites (tools/sdcard/mons/*.bin, made by pack_pmd.py) into
bitmap resources for the Garmin build. Run by fetch_sprites.py; on its own:

  python3 tools/garmin_sprites.py          # use whatever is packed
  python3 tools/garmin_sprites.py --empty  # back to the no-sprites placeholders

Writes garmin/sprites/: one idle-animation strip and one Pokédex thumbnail per
species, sprites.xml, and SpriteIds.mc. These are personal-use files: don't
commit them (git restore garmin/sprites puts the placeholders back).
"""
import os
import struct
import sys

from PIL import Image

TOOLS = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(TOOLS)
PACKED = os.path.join(TOOLS, 'sdcard', 'mons')
OUT = os.path.join(ROOT, 'garmin', 'sprites')
MAX_FRAMES = 6  # memory on the watch: a longer idle loop is cut short


def rgb(v):
    return ((v >> 11) & 31) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31


def read_idle(path):
    """Idle action (id 0) of a TPK2 file: w, h, ms[], frames[] (palette rgb or None)."""
    buf = open(path, 'rb').read()
    nacts = buf[4]
    (palcount,) = struct.unpack_from('<H', buf, 5)
    pal = [rgb(c) for c in struct.unpack_from(f'<{palcount}H', buf, 7)]
    p = 7 + palcount * 2
    for _ in range(nacts):
        aid, w, h, nf = buf[p], buf[p + 1], buf[p + 2], buf[p + 3]
        p += 4
        ms = list(struct.unpack_from(f'<{nf}H', buf, p))
        p += nf * 2
        if aid == 0:
            frames = []
            for f in range(nf):
                d = buf[p + f * w * h:p + (f + 1) * w * h]
                frames.append([None if k == 0xFF else pal[k] for k in d])
            return w, h, ms, frames
        p += w * h * nf
    raise ValueError('no Idle')


def scaled_image(w, h, frames, s):
    im = Image.new('RGBA', (w * s * len(frames), h * s), (0, 0, 0, 0))
    for fi, px in enumerate(frames):
        for y in range(h):
            for x in range(w):
                c = px[y * w + x]
                if c is None:
                    continue
                for dy in range(s):
                    for dx in range(s):
                        im.putpixel((fi * w * s + x * s + dx, y * s + dy), c + (255,))
    return im


def main():
    empty = '--empty' in sys.argv
    os.makedirs(OUT, exist_ok=True)
    for f in os.listdir(OUT):
        if f.endswith('.png'):
            os.remove(os.path.join(OUT, f))
    xml = ['<!-- GENERATED by tools/garmin_sprites.py (personal-use sprites: do not commit) -->',
           '<drawables>']
    info = {k: [0] * 152 for k in ('frames', 'fw', 'fh', 'base', 'ms', 'tw', 'th')}
    have = [False] * 152
    for dex in range(1, 152):
        path = os.path.join(PACKED, f'p{dex:03d}.bin')
        if empty or not os.path.exists(path):
            continue
        w, h, ms, frames = read_idle(path)
        frames, ms = frames[:MAX_FRAMES], ms[:MAX_FRAMES]
        # same zoom rule as the firmware's drawPmdAct (main screen, max x5)
        s = max(2, min(5, 170 // h if h else 5))
        while s > 2 and h * s > 250:
            s -= 1
        base = 1
        for px in frames:
            for r in range(h - 1, -1, -1):
                if any(px[r * w + c] is not None for c in range(w)):
                    base = max(base, r + 1)
                    break
        strip = scaled_image(w, h, frames, s)
        strip.save(os.path.join(OUT, f'm{dex:03d}.png'))
        pct_w = strip.width * 100 / 466
        pct_h = strip.height * 100 / 466
        xml.append(f'    <bitmap id="M{dex:03d}" filename="m{dex:03d}.png" scaleX="{pct_w:.3f}%" '
                   f'scaleY="{pct_h:.3f}%" scaleRelativeTo="screen" dithering="none" />')
        # Pokédex thumbnail: frame 0 fitted in 40x40, drawn x2 like the firmware's grid
        ts = min(40 / w, 40 / h, 1.0)
        tw, th = max(1, round(w * ts)), max(1, round(h * ts))
        thumb = scaled_image(w, h, frames[:1], 1).resize((tw, th), Image.NEAREST).resize((tw * 2, th * 2), Image.NEAREST)
        thumb.save(os.path.join(OUT, f't{dex:03d}.png'))
        xml.append(f'    <bitmap id="T{dex:03d}" filename="t{dex:03d}.png" scaleX="{tw * 200 / 466:.3f}%" '
                   f'scaleY="{th * 200 / 466:.3f}%" scaleRelativeTo="screen" dithering="none" />')
        have[dex] = True
        info['frames'][dex] = len(frames)
        info['fw'][dex] = w * s
        info['fh'][dex] = h * s
        info['base'][dex] = base * s
        info['ms'][dex] = round(sum(ms) / len(ms))
        info['tw'][dex] = tw * 2
        info['th'][dex] = th * 2
    xml += ['</drawables>']
    with open(os.path.join(OUT, 'sprites.xml'), 'w') as f:
        f.write('\n'.join(xml) + '\n')

    def arr(vals):
        return '[' + ', '.join(str(v) for v in vals) + ']'

    ids_m = ['null'] + [f'Rez.Drawables.M{d:03d}' if have[d] else 'null' for d in range(1, 152)]
    ids_t = ['null'] + [f'Rez.Drawables.T{d:03d}' if have[d] else 'null' for d in range(1, 152)]
    mc = ['// GENERATED by tools/garmin_sprites.py - do not edit, do not commit.',
          'import Toybox.Lang;', '', 'module SpriteIds {',
          '    // idle strip per species; sizes are in the firmware\'s 466 px space',
          f'    function strips() as Array {{ return {arr(ids_m)}; }}',
          f'    function thumbs() as Array {{ return {arr(ids_t)}; }}']
    for k in ('frames', 'fw', 'fh', 'base', 'ms', 'tw', 'th'):
        mc.append(f'    const {k.upper()} = {arr(info[k])} as Array<Number>;')
    mc.append('}')
    with open(os.path.join(OUT, 'SpriteIds.mc'), 'w') as f:
        f.write('\n'.join(mc) + '\n')
    print(f'Garmin: {sum(have)} species written to {os.path.relpath(OUT, ROOT)}')


if __name__ == '__main__':
    main()
